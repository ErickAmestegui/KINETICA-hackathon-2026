test('a late offline fit cannot overwrite changed model inputs',async({page})=>{
 await page.goto('/');await page.getByRole('button',{name:'My machines'}).click();
 const chooser=page.waitForEvent('filechooser');await page.getByRole('button',{name:'Open project JSON'}).click();
 await (await chooser).setFiles(path.resolve('../output/SYNTHETIC-mask-motion-project.json'));
 await expect(page.locator('.notification')).toContainText('Study restored');
 await page.getByRole('tab',{name:'Compare',exact:true}).click();
 await page.getByRole('button',{name:'Audit saved masks',exact:true}).click();
 await page.getByRole('button',{name:'Select #SYNTHETIC-SLIDER',exact:true}).click();
 await page.getByRole('checkbox',{name:/I inspected object/}).check();
 let release!:()=>void,started!:()=>void;
 const gate=new Promise<void>(resolve=>release=resolve),waiting=new Promise<void>(resolve=>started=resolve);
 await page.route('**/api/videos/*/mask-motion',async route=>{const response=await route.fetch();started();await gate;await route.fulfill({response});});
 await page.getByRole('button',{name:'Fit image projection only'}).click();await waiting;
 await page.getByRole('slider',{name:'Crank radius',exact:true}).fill('45');release();
 await expect(page.locator('.notification')).toContainText('stale results were discarded');
 await expect(page.getByRole('region',{name:'Saved mask motion analysis'})).toContainText('Model agreement: No evaluado');
});

test('explicit video-time fit synchronizes the model and keeps its retrospective interval',async({page})=>{
 await page.goto('/');await page.getByRole('button',{name:'My machines'}).click();
 const chooser=page.waitForEvent('filechooser');await page.getByRole('button',{name:'Open project JSON'}).click();
 await (await chooser).setFiles(path.resolve('../output/SYNTHETIC-mask-motion-project.json'));
 await expect(page.locator('.notification')).toContainText('Study restored');
 await page.getByRole('tab',{name:'Compare',exact:true}).click();
 await page.getByRole('button',{name:'Audit saved masks',exact:true}).click();
 await page.getByRole('button',{name:'Select #SYNTHETIC-SLIDER',exact:true}).click();
 await page.getByRole('checkbox',{name:/I inspected object/}).check();
 // Fixture is 30 video-rpm: this window includes >1.25 training cycles.
 await page.getByLabel('Last analysis frame').fill('109');
 await page.getByRole('checkbox',{name:/Estimate speed and phase/}).check();
 await page.getByRole('button',{name:'Fit timing and image projection',exact:true}).click();
 const panel=page.getByRole('region',{name:'Saved mask motion analysis'});
 await expect(panel).toContainText('Interval 0–109: manual; retrospective',{timeout:30000});
 await expect(panel).toContainText('0.00 px');
 const dl=page.waitForEvent('download');await page.getByRole('button',{name:'Export mask analysis',exact:true}).click();
 const report=JSON.parse(fs.readFileSync((await (await dl).path())!,'utf8'));
 expect(report.analysis.motion.timing_estimated).toBe(true);
 expect(report.parameters).toEqual(report.analysis.motion.parameters_used);
 expect(report.analysis.motion.validation_frames).toEqual(Array.from({length:27},(_,i)=>i+83));
 await page.getByRole('tab',{name:'Report',exact:true}).click();
 await expect(page.locator('.report-panel')).toContainText('timing estimated from training frames in video seconds');
 await page.getByRole('tab',{name:'Compare',exact:true}).click();
 await expect(panel).toContainText('Reserved 1D displacement RMSE');
});
